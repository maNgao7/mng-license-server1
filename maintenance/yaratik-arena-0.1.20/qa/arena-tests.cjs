'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const q=require('./commands.cjs');
const checks=[],captures=[],sleep=ms=>new Promise(r=>setTimeout(r,ms));
const original=JSON.parse(fs.readFileSync('../userdata/mod-settings.json','utf8'));
async function main(){
  await q.send('lock',{enabled:true});await q.send('native-resume');await q.send('menu',{open:false});await q.send('reset');
  assert.equal(q.state().pitCovered,true);assert.ok(q.state().removedMachines>=1);
  checks.push('Original center machine is hidden and a native factory floor cover seals the pit');
  await q.send('view',{x:10,z:-8,yaw:-55,pitch:12});
  await q.send('spawn',{count:50,user:'QA hidden-name'});
  const wave=await q.wait(s=>s.Alive===50&&s.pending===0,'Fifty arena arrivals');
  assert.ok(wave.arrivalEffects>0);
  assert.ok(wave.recentArrivals.every(p=>Math.abs(p.x)<=21&&Math.abs(p.z)<=22&&p.y>=.3&&p.y<=1));
  assert.ok(Object.keys(wave.creatureModels).length===9);
  captures.push({kind:'center-covered-native-creatures',seq:(await q.send('capture')).seq});
  checks.push('Nine unchanged native creature variants arrive only on flat open central ground, with pooled soft impact effects');
  await q.send('reset');await q.send('crowd-settings',{total:1000000,physical:60,timed:false});
  const start=Date.now();await q.send('spawn',{count:1000000,user:'QA million'});
  const crowded=await q.wait(s=>s.Alive===60&&s.pending===2440,'Physical budget and capped backlog',15000);
  assert.equal(crowded.logicalAlive,2500);assert.equal(crowded.pendingBatches,1);assert.equal(crowded.failed,false);assert.equal(crowded.hudError,'');
  await q.send('spawn',{count:1000});assert.equal(q.state().logicalAlive,2500);
  captures.push({kind:'capped-logical-counter',seq:(await q.send('capture')).seq});
  checks.push('Oversized waves cap at 2500, never exceed sixty physical creatures, and reject overflow');
  await q.send('kill',{count:10});
  const replacement=await q.wait(s=>s.Alive===60&&s.pending===2430,'Backlog replenishes dead physical creatures',8000);
  assert.equal(replacement.logicalAlive,2490);assert.equal(replacement.Kills,10);assert.equal(replacement.Won,false);
  checks.push('Actual kills decrement the counter exactly; queued creatures replenish without a false win');
  await q.send('reset');await q.send('crowd-settings',{total:1000,physical:60,timed:true,seconds:1});
  await q.send('spawn',{count:1});await q.wait(s=>s.Alive===1,'Timed participant');
  await q.send('challenge-start');
  await q.send('menu',{tab:3,optionPage:2,open:true});
  await q.wait(s=>s.menuRendered&&!s.hudError,'Timed settings render');
  captures.push({kind:'round-settings',seq:(await q.send('capture')).seq});
  const t=q.state().challenge.remaining;await sleep(1600);assert.equal(q.state().roundTimedOut,false);assert.equal(q.state().challenge.remaining,t);
  await q.send('menu',{open:false});
  const timeout=await q.wait(s=>s.roundTimedOut,'Timed round ends',14000);
  assert.equal(timeout.Won,false);
  captures.push({kind:'time-limit',seq:(await q.send('capture')).seq});
  checks.push('P starts a ten-second preparation; B pauses it and the task times out without a false win');
  await q.wait(s=>!s.roundTimedOut&&s.Alive===0&&s.pending===0,'Timed reset',7000);
  checks.push('Timed round resets to an empty arena');
  await q.send('crowd-settings',{total:original.MaxCreatures,physical:original.PhysicalCreatures||180,timed:original.TimedMode||false,seconds:original.RoundSeconds||120});
  await q.send('reset');await q.send('lock',{enabled:false});
  fs.writeFileSync('arena-result.json',JSON.stringify({passed:true,checks,captures,millionFillMs:Date.now()-start},null,2));
  console.log(JSON.stringify({passed:true,checks,captures}));
}
main().catch(async error=>{fs.writeFileSync('arena-result.json',JSON.stringify({passed:false,error:error.stack,checks,captures,state:q.state()},null,2));try{await q.send('crowd-settings',{total:original.MaxCreatures,physical:original.PhysicalCreatures||180,timed:original.TimedMode||false,seconds:original.RoundSeconds||120});await q.send('menu',{open:false});await q.send('reset');await q.send('lock',{enabled:false});}catch{}console.error(error);process.exitCode=1;});
