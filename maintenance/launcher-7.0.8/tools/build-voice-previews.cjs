'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {createChatterboxRuntime}=require('../lib/chatterbox-runtime.cjs');
const {createVoicePackManager,CATALOG}=require('../lib/voice-pack-manager.cjs');
const {createSpeechService}=require('../lib/speech-service.cjs');
const sample=require('../renderer/speech-previews.js');
const root=process.env.MNG_CHATTERBOX_ROOT||'D:/TikMnG-Chatterbox-v3-ready';
const output=path.resolve(__dirname,'../renderer/assets/voice-previews');
const runtime=createChatterboxRuntime({root,timeoutMs:240000});
const packs=createVoicePackManager({root:path.join(process.env.APPDATA,'TikMnG-Test-6.5.17/voices/v1')});
const service=createSpeechService({voicePacks:packs,windowsRunner:async()=>[]});
const hash=data=>crypto.createHash('sha256').update(data).digest('hex');
async function main(){
    fs.mkdirSync(output,{recursive:true});
    const manifestFile=path.join(output,'manifest.json');
    let old;
    try{old=JSON.parse(fs.readFileSync(manifestFile,'utf8'));}catch{}
    const manifest={version:1,text:sample.text,spokenText:sample.spokenText,voices:[],attribution:'Natural voices: Alania Turkish Synthetic Speech by PatientDesk AI, CC BY 4.0. Generated by TikMnG using Chatterbox. Okur: Ahmet Hakan Besel, CC BY 4.0. EMA: Canberk Aslan, Apache 2.0.',licenseURL:'https://creativecommons.org/licenses/by/4.0/',source:'https://huggingface.co/datasets/cloud0day3/alania-synthetic-speech-tr',revision:'277dfc8a2322014099ff72688bcaee12480c4605',changes:'Reference clips used to generate new Turkish demonstration sentences; local speaker display names added. Chatterbox watermark retained.'};
    const definitions=[...require('../lib/chatterbox-voices.json').map(voice=>({...voice,voiceURI:'chatterbox:'+voice.id,provider:'chatterbox'})),...CATALOG.map(pack=>({...pack,provider:'offline'}))];
    for(const voice of definitions){
        const filename=sample.files[voice.voiceURI],target=path.join(output,filename);
        const previous=old?.spokenText===sample.spokenText&&old.voices?.find(item=>item.voiceURI===voice.voiceURI);
        let wav;
        if(previous&&fs.existsSync(target)&&hash(fs.readFileSync(target))===previous.sha256)wav=fs.readFileSync(target);
        else{
            const started=Date.now();
            console.log('Generating',voice.name);
            wav=voice.provider==='chatterbox'?await runtime.synthesize({text:sample.spokenText,voiceURI:voice.voiceURI,rate:1}):Buffer.from((await service.synthesize({text:sample.spokenText,voiceURI:voice.voiceURI,provider:'offline',voicePreset:'natural',rate:1})).audioBase64,'base64');
            if(wav.toString('ascii',0,4)!=='RIFF'||wav.length<1000)throw new Error('Invalid preview: '+voice.id);
            fs.writeFileSync(target,wav);console.log('Generated',voice.name,Date.now()-started,'ms',wav.length,'bytes');
        }
        manifest.voices.push({id:voice.id,name:voice.name,voiceURI:voice.voiceURI,file:filename,bytes:wav.length,sha256:hash(wav)});
        fs.writeFileSync(manifestFile,JSON.stringify(manifest,null,2));
    }
    if(manifest.voices.length!==12)throw new Error('Preview set incomplete');
    console.log('All 12 voice previews ready:',output);
}
main().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{runtime.close();service.close();packs.close();});
