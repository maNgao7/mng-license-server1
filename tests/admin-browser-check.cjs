const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const net = require('node:net');
const { spawn } = require('node:child_process');
const assert = require('node:assert/strict');

async function main() {
    const playwrightPath = process.env.PLAYWRIGHT_MODULE || 'playwright';
    const { chromium } = require(playwrightPath);
    const root = path.resolve(__dirname, '..');
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tikmng-admin-browser-'));
    for (const name of ['lisanslar', 'lisanslar_backup', 'aktivasyon_log', 'talepler', 'kara_liste']) fs.writeFileSync(path.join(dir, name + '.json'), '[]');
    const secret = crypto.randomBytes(32).toString('hex');
    const port = await new Promise(resolve => {
        const server = net.createServer().listen(0, '127.0.0.1', () => {
            const port = server.address().port;
            server.close(() => resolve(port));
        });
    });
    const env = { ...process.env, HOST: '127.0.0.1', PORT: String(port), MNG_DATA_DIR: dir, ADMIN_SIFRE: secret,
        GITHUB_TOKEN: '', GITHUB_LICENSE_TOKEN: '', GITHUB_LICENSE_REPO: '', BACKUP_REPO: '' };
    const child = spawn(process.execPath, ['server.js'], { cwd: root, env, windowsHide: true, stdio: 'ignore' });
    let browser;
    try {
        const base = `http://127.0.0.1:${port}`;
        for (let i = 0; i < 100; i++) {
            try { if ((await fetch(base + '/api/health')).ok) break; } catch {}
            await new Promise(resolve => setTimeout(resolve, 50));
        }
        console.log('Isolated fixture server ready');
        browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE, timeout: 60000 });
        console.log('Browser ready');
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(base + '/admin/');
        await page.locator('#adminPassword').fill(secret);
        await page.getByRole('button', { name: 'Giriş yap', exact: true }).click();
        await page.locator('#adminPanel').waitFor({ state: 'visible' });
        await page.locator('#syncStatus').filter({ hasText: 'Güncel' }).waitFor();
        console.log('Admin login passed');
        await page.locator('#agencyName').fill('Trend Ajans');
        await page.locator('#agencyCapacity').fill('20');
        await page.locator('#licenseNote').fill('Yayıncı ekibi');
        await page.getByRole('button', { name: 'Ajans lisansı oluştur', exact: true }).click();
        await page.locator('#newLicense').waitFor({ state: 'visible' });
        const code = await page.locator('#newCode').textContent();
        assert.match(code, /^TRENDAJ-/);
        assert.ok(code.length <= 25);
        assert.ok(!code.includes('HYPE'));
        for (let i = 1; i <= 3; i++) {
            const result = await context.request.post(base + '/api/license/verify', { data: { code, deviceId: 'preview-device-' + i } });
            assert.equal((await result.json()).valid, true);
        }
        await page.locator('#refresh').click();
        await page.locator('#syncStatus').filter({ hasText: 'Güncel' }).waitFor();
        await page.getByRole('button', { name: 'Trend Ajans yayıncılarını göster' }).click();
        await page.locator('.member-name').first().waitFor();
        assert.equal(await page.locator('.member-name').count(), 3);
        await page.locator('.member-name input').first().fill('Deniz');
        await page.locator('.member-name button').first().click();
        await page.waitForFunction(() => document.querySelector('.member-name input')?.value === 'Deniz' && !document.querySelector('#refresh').disabled);
        await page.locator('.capacity-form input').fill('25');
        await page.locator('.capacity-form button').click();
        await page.waitForFunction(() => document.querySelector('.detail-header h3')?.textContent.includes('3 / 25'));
        console.log('Agency creation, expansion, member label and capacity passed');
        const out = path.join(root, 'qa', 'admin-2026-10-21');
        fs.mkdirSync(out, { recursive: true });
        await page.screenshot({ path: path.join(out, 'admin-desktop.png'), fullPage: true });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        await page.setViewportSize({ width: 390, height: 844 });
        await page.screenshot({ path: path.join(out, 'admin-mobile.png'), fullPage: true });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        console.log('Desktop and mobile overflow checks passed');
        await page.setViewportSize({ width: 1440, height: 1000 });
        await page.locator('[data-mode="standard"]').click();
        assert.equal(await page.locator('#agencyNameField').isVisible(), false);
        await page.locator('#individualName').fill('Deniz Yayinci');
        await page.locator('#createButton').click();
        await page.waitForFunction(() => document.getElementById('newCode').textContent.startsWith('MNG30D-'));
        await page.locator('.license-title span').filter({ hasText: 'Deniz Yayinci' }).waitFor();
        console.log('Individual license format unchanged');
        await page.locator('[data-view="agencies"]').click();
        page.once('dialog', dialog => dialog.accept());
        await page.locator('[data-action="block"]').first().click();
        await page.waitForFunction(() => document.querySelectorAll('.member-name').length === 2);
        const blockedResult = await context.request.post(base + '/api/license/verify', { data: { code, deviceId: 'preview-device-1' } });
        assert.equal((await blockedResult.json()).valid, false);
        await page.locator('.blocked-members summary').click();
        page.once('dialog', dialog => dialog.accept());
        await page.locator('[data-action="unblock"]').click();
        await page.waitForFunction(() => !document.querySelector('.blocked-members'));
        const allowedResult = await context.request.post(base + '/api/license/verify', { data: { code, deviceId: 'preview-device-1' } });
        assert.equal((await allowedResult.json()).valid, true);
        await page.locator('#refresh').click();
        await page.waitForFunction(() => document.querySelectorAll('.member-name').length === 3);
        console.log('Member block, access rejection and re-allow passed');
        const downloadPromise = page.waitForEvent('download');
        await page.locator('#export').click();
        const download = await downloadPromise;
        const backup = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
        assert.equal(backup.length, 2);
        page.once('dialog', dialog => dialog.accept());
        await page.locator('#importFile').setInputFiles({ name: 'test-backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
        await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('0 lisans eklendi'));
        console.log('Backup export and merge without duplicate licenses passed');
        const xssName = '<img src=x onerror="window.__xss=true">';
        await context.request.post(base + '/api/admin/ajans-lisansi-olustur', { data: { ajans_adi: xssName, max_yayinci: 2, sure_birim: 'gun', sure_miktar: 7 } });
        await page.locator('#refresh').click();
        await page.waitForFunction(() => document.querySelector('#licensesBody').textContent.includes('<img src=x'));
        assert.equal(await page.evaluate(() => Boolean(window.__xss)), false);
        assert.equal(await page.locator('#licensesBody img').count(), 0);
        await page.locator('#search').fill('Trend');
        await page.locator('[data-action="copy"]').first().waitFor();
        await page.locator('#search').fill('no-such-license');
        assert.equal(await page.locator('#licensesBody').textContent(), 'Bu filtrede lisans bulunamadı.');
        await page.locator('#search').fill('');
        console.log('Search, empty state and stored XSS escaping passed');
        await page.route('**/api/admin/lisanslar', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Deneme bağlantı hatası' }) }));
        await page.locator('#refresh').click();
        await page.locator('#pageError').waitFor({ state: 'visible' });
        await page.unroute('**/api/admin/lisanslar');
        await page.locator('#refresh').click();
        await page.waitForFunction(() => document.getElementById('pageError').hidden);
        console.log('Connection failure and recovery passed');
        await page.locator('[data-view="licenses"]').click();
        const created = await context.request.post(base + '/api/admin/lisans-olustur', {
            data: { ad: 'Sure Denemesi', sure_birim: 'gun', sure_miktar: 7, notlar: 'Ilk not' }
        });
        assert.ok(created.ok());
        const editCode = (await created.json()).kod;
        const activated = await context.request.post(base + '/api/license/verify', { data: { code: editCode, deviceId: 'browser-edit-device' } });
        const originalEnd = (await activated.json()).expiresAt;
        const record = async key => (await (await context.request.get(base + '/api/admin/lisanslar')).json()).find(l => l.kod === key);
        const row = page.locator(`tr[data-license="${editCode}"]`);
        const editor = page.locator('.license-editor-form');
        const refreshList = async () => {
            const loaded = page.waitForResponse(response => response.url() === base + '/api/admin/talepler' && response.request().method() === 'GET');
            await page.locator('#refresh').click();
            await loaded;
            await page.waitForFunction(() => !document.querySelector('#refresh').disabled);
        };
        const saveEditor = async () => {
            await editor.getByRole('button', { name: 'Değişiklikleri kaydet', exact: true }).click();
            await editor.waitFor({ state: 'detached' });
            await page.waitForFunction(() => !document.querySelector('#refresh').disabled);
        };
        await refreshList();
        await row.locator('[data-action="edit"]').click();
        assert.equal(await editor.locator('[name="changeDuration"]').isChecked(), false);
        assert.equal(await editor.locator('[name="operation"]').isDisabled(), true);
        await editor.locator('[name="ad"]').fill('Deniz Yeni Isim');
        await editor.locator('[name="notlar"]').fill('Yeni gorunur musteri notu');
        await saveEditor();
        assert.equal((await record(editCode)).bitis_zamani, originalEnd);
        assert.equal(await row.locator('.license-title span').textContent(), 'Deniz Yeni Isim');
        assert.equal(await row.locator('.note-content strong').textContent(), 'Yeni gorunur musteri notu');
        console.log('Individual name creation and inline name/note editing preserve expiration');
        const adjustDuration = async (operation, amount, unit = 'gun') => {
            await row.locator('[data-action="edit-time"]').click();
            assert.equal(await editor.locator('[name="changeDuration"]').isChecked(), true);
            await editor.locator('[name="operation"]').selectOption(operation);
            await editor.locator('[name="amount"]').fill(String(amount));
            await editor.locator('[name="unit"]').selectOption(unit);
            await saveEditor();
            return record(editCode);
        };
        const reset = await adjustDuration('ayarla', 7);
        assert.equal(reset.sure_miktar, 7);
        assert.ok(Math.abs(reset.bitis_zamani - Date.now() - 7 * 86400000) < 5000);
        const increased = await adjustDuration('ekle', 2);
        assert.equal(increased.bitis_zamani, reset.bitis_zamani + 2 * 86400000);
        const decreased = await adjustDuration('azalt', 1);
        assert.equal(decreased.bitis_zamani, increased.bitis_zamani - 86400000);
        assert.equal(decreased.sure_miktar, 7);
        const hourAdded = await adjustDuration('ekle', 1, 'saat');
        assert.equal(hourAdded.bitis_zamani, decreased.bitis_zamani + 3600000);
        console.log('Duration reset, increase, decrease and hour conversion passed through UI');
        await row.locator('[data-action="edit-time"]').click();
        await editor.scrollIntoViewIfNeeded();
        await page.screenshot({ path: path.join(out, 'license-editor-desktop.png'), fullPage: true });
        for (const width of [390, 320]) {
            await page.setViewportSize({ width, height: 844 });
            await editor.evaluate(form => { form.closest('.table-scroll').scrollLeft = 0; });
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
            assert.ok(await editor.evaluate(form => [...form.querySelectorAll('input,select,textarea,button')].every(control => {
                const rect = control.getBoundingClientRect();
                return rect.left >= 0 && rect.right <= innerWidth;
            })), 'All inline editor controls fit the mobile viewport');
        }
        await page.screenshot({ path: path.join(out, 'license-editor-mobile.png'), fullPage: true });
        await editor.locator('[data-action="cancel-edit"]').click();
        await page.setViewportSize({ width: 1440, height: 1000 });
        const expired = await adjustDuration('azalt', 20);
        assert.equal(expired.durum, 'suresi_doldu');
        await row.locator('.state').filter({ hasText: 'Süresi dolmuş' }).waitFor();
        page.once('dialog', dialog => dialog.accept());
        await row.locator('[data-action="renew"]').click();
        await row.locator('.state').filter({ hasText: /^Aktif$/ }).waitFor();
        const renewed = await record(editCode);
        assert.ok(Math.abs(renewed.bitis_zamani - Date.now() - 7 * 86400000) < 5000);
        assert.equal(renewed.cihaz_kimlik, 'browser-edit-device');
        page.once('dialog', dialog => dialog.accept());
        await row.locator('[data-action="renew"]').click();
        await row.locator('.time-cell > .muted').filter({ hasText: '14 gün kaldı' }).waitFor();
        assert.equal((await record(editCode)).bitis_zamani, renewed.bitis_zamani + 7 * 86400000);
        console.log('Expired renewal and active renewal retaining remaining time passed through UI');
        const unlimitedResponse = await context.request.post(base + '/api/admin/lisans-olustur', {
            data: { ad: 'Silinecek Sinirsiz', sure_birim: 'sinirsiz', sure_miktar: -1 }
        });
        assert.ok(unlimitedResponse.ok());
        const unlimitedCode = (await unlimitedResponse.json()).kod;
        const unlimitedRow = page.locator(`tr[data-license="${unlimitedCode}"]`);
        await context.request.post(base + '/api/license/verify', { data: { code: unlimitedCode, deviceId: 'browser-delete-device' } });
        await refreshList();
        await unlimitedRow.waitFor();
        const countBefore = Number(await page.locator('#licenseCount').textContent());
        page.once('dialog', dialog => dialog.accept());
        await unlimitedRow.locator('[data-action="archive"]').click();
        await unlimitedRow.waitFor({ state: 'detached' });
        assert.equal(Number(await page.locator('#licenseCount').textContent()), countBefore - 1);
        await page.reload();
        await page.locator('#syncStatus').filter({ hasText: 'Güncel' }).waitFor();
        assert.equal(await unlimitedRow.count(), 0);
        const denied = await context.request.post(base + '/api/license/verify', { data: { code: unlimitedCode, deviceId: 'browser-delete-device' } });
        assert.equal((await denied.json()).valid, false);
        await page.locator('#statusFilter').selectOption('arsivlendi');
        await unlimitedRow.waitFor();
        assert.equal(await unlimitedRow.locator('[data-action]').count(), 0);
        assert.equal(await unlimitedRow.locator('.state').textContent(), 'Kalıcı olarak silindi');
        await page.locator('#statusFilter').selectOption('all');
        assert.equal(await unlimitedRow.count(), 0);
        console.log('Permanent deletion hides unlimited licenses, survives reload and denies access; audit cannot reopen');
        await page.goto(base + '/');
        await page.waitForFunction(() => document.querySelector('#heroCanvas')?.width > 0);
        const demoBox = await page.locator('#sim').boundingBox();
        const navBox = await page.locator('.nav-header').boundingBox();
        assert.ok(demoBox.y >= navBox.y + navBox.height, 'Demo must not overlap fixed navigation');
        assert.equal(await page.locator('.hero #sim').count(), 0);
        assert.ok(demoBox.y >= (await page.locator('.hero').boundingBox()).height, 'Demo belongs below the hero artwork');
        assert.equal(await page.locator('#adminEntry').getAttribute('href'), '/admin/');
        assert.ok(await page.locator('#heroCanvas').evaluate(canvas => {
            const pixels = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
            let lit = 0;
            for (let i = 0; i < pixels.length; i += 64) if (pixels[i] > 70 || pixels[i + 1] > 70 || pixels[i + 2] > 70) lit++;
            return lit > 20;
        }), 'Relocated demo still paints its active game');
        await page.screenshot({ path: path.join(out, 'website-desktop.png') });
        for (const viewport of [{ width: 2560, height: 1280 }, { width: 1920, height: 1080 }, { width: 1366, height: 768 }, { width: 390, height: 844 }, { width: 320, height: 568 }]) {
            await page.setViewportSize(viewport);
            const entry = await page.locator('#adminEntry').boundingBox();
            const logo = await page.locator('.brand-logo').first().boundingBox();
            assert.ok(await page.locator('#adminEntry').isVisible(), 'Admin entry remains visible at ' + viewport.width);
            assert.ok(entry.x >= logo.x + logo.width, 'Admin entry must not collide with the logo');
            assert.ok(entry.x + entry.width <= viewport.width && entry.y >= 0, 'Admin entry remains in the viewport');
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
            const hero = await page.locator('.hero').boundingBox();
            assert.ok(hero.height >= viewport.height - 35, 'Artwork fills the first viewport');
            assert.ok(hero.height < viewport.height, 'The next section stays visible at ' + viewport.width + ' pixels');
            const imageLoaded = await page.evaluate(async () => {
                const image = new Image();
                image.src = '/portal-hero-v2.png';
                await image.decode();
                return image.naturalWidth > 1000;
            });
            assert.ok(imageLoaded);
            if (viewport.width === 2560) await page.screenshot({ path: path.join(out, 'website-wide.png') });
        }
        console.log('Visible admin entry, full-height artwork and non-overlap passed at five viewport sizes');
        await page.setViewportSize({ width: 390, height: 844 });
        await page.screenshot({ path: path.join(out, 'website-mobile.png') });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        await page.locator('#portalMenu').click();
        assert.equal(await page.locator('#primaryNavigation').isVisible(), true);
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('#primaryNavigation').isVisible(), false);
        await page.locator('#ad').fill('Test Yayinci');
        await page.locator('#iletisim').fill('test@example.invalid');
        await page.locator('#tur').selectOption('lisans');
        await page.locator('#mesaj').fill('Ajans lisansi icin test talebi.');
        await page.locator('#talepSubmitBtn').click();
        await page.locator('#talepStatus').filter({ hasText: /iletil|iletildi|gönderildi|gönderil/i }).waitFor();
        await page.goto(base + '/admin/');
        await page.locator('[data-view="requests"]').click();
        await page.locator('#requestsBody').filter({ hasText: 'Test Yayinci' }).waitFor();
        await page.getByRole('button', { name: 'Lisans hazırla', exact: true }).click();
        assert.equal(await page.locator('#licenseNote').inputValue(), 'Test Yayinci (test@example.invalid)');
        console.log('Public mobile menu, inquiry form and admin request-to-license flow passed');
        const guest = await browser.newContext({ viewport: { width: 390, height: 844 } });
        const guestPage = await guest.newPage();
        await guestPage.goto(base + '/');
        await guestPage.locator('.nav-header').getByRole('link', { name: 'Yönetici Girişi', exact: true }).click();
        await guestPage.locator('#loginPage').waitFor({ state: 'visible' });
        assert.equal(await guestPage.locator('#adminPassword').isVisible(), true);
        await guest.close();
        console.log('Public admin entry opens the protected login screen');
        assert.deepEqual(errors, []);
        fs.writeFileSync(path.join(out, 'browser-result.json'), JSON.stringify({ checkedAt: new Date().toISOString(), errors, checks: ['admin login', '25-character agency key naming', 'agency expansion', 'member rename', 'capacity save', 'desktop overflow', 'mobile overflow', 'individual legacy format', 'member block and unblock', 'backup export and import', 'XSS escaping', 'search', 'empty state', 'connection recovery', 'individual customer name creation', 'inline name and note editing preserves expiration', 'duration reset, increase and decrease', 'hour duration conversion', 'inline editor desktop and mobile framing', 'expired renewal', 'active renewal preserves remaining time', 'deleted unlimited license hidden after reload and denied access', 'deleted audit is read-only', 'public navigation framing', 'public mobile menu', 'public inquiry form', 'admin request-to-license flow', 'visible admin entry across five viewport sizes', 'full-height artwork and active demo below hero', 'guest admin entry opens protected login'] }, null, 2));
        console.log('Browser checks passed. Screenshots: ' + out);
    } finally {
        if (browser) await browser.close();
        await new Promise(resolve => { child.once('exit', resolve); child.kill(); });
        const safeRoot = path.join(os.tmpdir(), 'tikmng-admin-browser-');
        if (dir.startsWith(safeRoot)) fs.rmSync(dir, { recursive: true, force: true });
    }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
